"""
Unsupervised PPG Feature Clustering (K-Means + PCA)
===================================================
Exploratory morphological subtyping and feature representation learning.

CRITICAL MEDICAL NOTICE:
Cluster assignments generated by this module are purely geometric and mathematical groupings
of optical pulse waveforms. They DO NOT represent clinical diagnoses, Coronary Artery Disease,
or medical pathology without downstream clinical validation.
"""

from typing import Dict, Any, List, Optional, Tuple, Union
import numpy as np
import pandas as pd
from sklearn.cluster import KMeans
from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA
from sklearn.metrics import silhouette_score


class PPGUnsupervisedClusterer:
    """
    K-Means clustering and PCA dimensionality reduction for exploratory PPG profiling.
    """

    def __init__(
        self,
        n_clusters: int = 4,
        use_pca: bool = True,
        n_components: int = 6,
        random_state: int = 42,
    ):
        """
        Parameters
        ----------
        n_clusters : int
            Number of morphological clusters (k).
        use_pca : bool
            Whether to apply PCA before clustering.
        n_components : int
            Number of PCA principal components to retain.
        random_state : int
            Reproducibility seed.
        """
        self.n_clusters = n_clusters
        self.use_pca = use_pca
        self.n_components = n_components
        self.random_state = random_state

        self.scaler = StandardScaler()
        self.pca = PCA(n_components=n_components, random_state=random_state) if use_pca else None
        self.kmeans = KMeans(n_clusters=n_clusters, random_state=random_state, n_init=10)

        self.feature_names: List[str] = []
        self.is_fitted: bool = False

    def fit(self, X: Union[pd.DataFrame, np.ndarray]) -> "PPGUnsupervisedClusterer":
        """
        Fit scaler, PCA (optional), and KMeans on PPG feature matrix.
        """
        if isinstance(X, pd.DataFrame):
            # Exclude non-feature identifier columns if present
            meta_cols = {"file_id", "patient_id", "label", "target", "device_bpm_ref"}
            feat_cols = [c for c in X.columns if c not in meta_cols]
            self.feature_names = feat_cols
            X_arr = X[feat_cols].to_numpy(dtype=np.float32)
        else:
            X_arr = np.asarray(X, dtype=np.float32)
            self.feature_names = [f"feat_{i}" for i in range(X_arr.shape[1])]

        X_arr = np.nan_to_num(X_arr, nan=0.0, posinf=0.0, neginf=0.0)

        # Scale features
        X_scaled = self.scaler.fit_transform(X_arr)

        # PCA transformation
        if self.use_pca and self.pca is not None:
            n_samples, n_feats = X_scaled.shape
            actual_components = min(self.n_components, n_samples, n_feats)
            self.pca.set_params(n_components=actual_components)
            X_repr = self.pca.fit_transform(X_scaled)
        else:
            X_repr = X_scaled

        # Fit KMeans
        self.kmeans.fit(X_repr)
        self.is_fitted = True
        return self

    def predict_clusters(self, X: Union[pd.DataFrame, np.ndarray]) -> np.ndarray:
        """
        Assign cluster IDs (0 to k-1).
        """
        if not self.is_fitted:
            raise RuntimeError("Clusterer is not fitted yet. Call fit() first.")

        X_repr = self._preprocess_input(X)
        return self.kmeans.predict(X_repr)

    def transform_to_cluster_distances(self, X: Union[pd.DataFrame, np.ndarray]) -> np.ndarray:
        """
        Transform feature matrix into distances to each cluster centroid.
        These soft distance features can be directly appended to the supervised classifier!

        Returns
        -------
        np.ndarray shape (N, n_clusters): Euclidean distances to each cluster centroid.
        """
        if not self.is_fitted:
            raise RuntimeError("Clusterer is not fitted yet. Call fit() first.")

        X_repr = self._preprocess_input(X)
        return self.kmeans.transform(X_repr)

    def get_pca_projection(self, X: Union[pd.DataFrame, np.ndarray], n_dims: int = 2) -> np.ndarray:
        """
        Project features onto 2D or 3D space for visualization.
        """
        if not self.is_fitted:
            raise RuntimeError("Clusterer is not fitted yet.")

        X_arr = self._clean_array(X)
        X_scaled = self.scaler.transform(X_arr)
        if self.pca is not None:
            proj = self.pca.transform(X_scaled)
            return proj[:, :n_dims]
        else:
            return X_scaled[:, :n_dims]

    def _preprocess_input(self, X: Union[pd.DataFrame, np.ndarray]) -> np.ndarray:
        X_arr = self._clean_array(X)
        X_scaled = self.scaler.transform(X_arr)
        if self.use_pca and self.pca is not None:
            return self.pca.transform(X_scaled)
        return X_scaled

    def _clean_array(self, X: Union[pd.DataFrame, np.ndarray]) -> np.ndarray:
        if isinstance(X, pd.DataFrame):
            if self.feature_names:
                # Reindex to exact feature names in fitted order, filling missing with 0.0
                X_arr = X.reindex(columns=self.feature_names, fill_value=0.0).to_numpy(dtype=np.float32)
            else:
                meta_cols = {"file_id", "patient_id", "label", "target", "device_bpm_ref"}
                cols = [c for c in X.columns if c not in meta_cols]
                X_arr = X[cols].to_numpy(dtype=np.float32)
        else:
            X_arr = np.asarray(X, dtype=np.float32)
        return np.nan_to_num(X_arr, nan=0.0, posinf=0.0, neginf=0.0)

    @staticmethod
    def evaluate_clustering(
        X: Union[pd.DataFrame, np.ndarray],
        k_range: Tuple[int, int] = (2, 7),
    ) -> List[Dict[str, float]]:
        """
        Evaluate clustering across multiple k values using Inertia (Elbow method) and Silhouette Score.
        """
        X_arr = np.asarray(X, dtype=np.float32)
        X_arr = np.nan_to_num(X_arr, nan=0.0)
        scaler = StandardScaler()
        X_scaled = scaler.fit_transform(X_arr)

        results = []
        for k in range(k_range[0], k_range[1] + 1):
            if k >= len(X_arr):
                break
            km = KMeans(n_clusters=k, random_state=42, n_init=5)
            labels = km.fit_predict(X_scaled)
            inertia = float(km.inertia_)
            sil = float(silhouette_score(X_scaled, labels)) if len(np.unique(labels)) > 1 else 0.0
            results.append({"k": k, "inertia": inertia, "silhouette": round(sil, 4)})

        return results
